# 1) 输入姓名（字符串，不用转）
name = input("姓名：")

# 2) 输入三门成绩（整数，用 int 转）
s1 = int(input("高数成绩："))
s2 = int(input("Python 成绩："))
s3 = int(input("英语成绩："))

# 3) 计算平均分（用 / 才能出小数，结果用 float）
avg = (s1 + s2 + s3) / 3

# 4) 判断是否及格（平均分 >= 60）
# TODO: 用比较运算符写一句，把结果存到变量 passed 里
passed = avg >= 60

# 5) 打印：姓名 + 平均分 + 是否及格
print(name + " 的平均分是 " + str(avg) + "，是否及格：" + str(passed))
