# ---------- 练习 1：姓名 + 明年年龄（类型转换） ----------
name = input("请输入你的名字：")
age = int(input("请输入你的年龄："))   # 必须 int()，否则 age+1 会拼字符串
print("你好，" + name + "，明年你就", age + 1, "岁了")


# ---------- 练习 2：食堂买麻辣烫（// 和 %） ----------
money = 33
price = 9
print("能买", money // price, "份，剩", money % price, "元")
# 33 // 9 = 3，33 % 9 = 6 → 能买 3 份，剩 6 元


# ---------- 练习 3：三门课平均分 + 是否全及格（比较 + 逻辑） ----------
s1 = int(input("高数成绩："))
s2 = int(input("Python 成绩："))
s3 = int(input("英语成绩："))
avg = (s1 + s2 + s3) / 3          # 用 / 才能出小数
all_pass = (s1 >= 60) and (s2 >= 60) and (s3 >= 60)  # 三门都>=60 才是全及格
print("平均分：", avg)
print("是否全部及格：", all_pass)
